
public class Circle 
{
	//Instance variables
	//number will never change
	private static final double PI = 3.14;
	private double radius;
	
	//Constructor method
	public Circle()
	{
		radius = 1.0;
	}
	
	//Overload Constructor method
	public Circle(double r) 
	{
		radius = r;	
	}
	
	
}
